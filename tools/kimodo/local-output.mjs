function readFloats(path) {
	const bytes = readFileSync(path);
	if (bytes.length === 0 || bytes.length % 4 !== 0) {
		throw new Error(`writeLocalKimodoNpz: ${path} must contain nonempty float32 bytes`);
	}
	const values = new Float32Array(bytes.length / 4);
	for (let i = 0; i < values.length; i++) {
		values[i] = bytes.readFloatLE(i * 4);
		if (!Number.isFinite(values[i])) {
			throw new Error(`writeLocalKimodoNpz: ${path} has non-finite float at index ${i}`);
		}
	}
	return values;
}

function quaternionMatrix(values, offset, frame, joint) {
	let [x, y, z, w] = values.subarray(offset, offset + 4);
	const norm = Math.hypot(x, y, z, w);
	if (norm === 0) {
		throw new Error(`writeLocalKimodoNpz: local_rotations_xyzw.f32 has zero quaternion at frame ${frame}, joint ${joint}`);
	}
	// Both q and -q, and any finite nonzero scaling, represent the same rotation.
	x /= norm; y /= norm; z /= norm; w /= norm;
	return [
		1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w),
		2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w),
		2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y),
	];
}

/**
 * Synchronously validate local files and write native SOMA77 NPZ members
 * posed_joints [T,77,3], global_rot_mats [T,77,3,3], and scalar fps=30.
 * No output is written until all input and computed arrays have been validated.
 * @param {string} outputDir Directory containing the two little-endian .f32 files.
 * @param {string} npzPath Destination NPZ (its parent directory must exist).
 * @param {{expectedFrames?: number}} [options] Optional requested frame count.
 */
export function writeLocalKimodoNpz(outputDir, npzPath, { expectedFrames } = {}) {
	if (endianness() !== "LE") throw new Error("writeLocalKimodoNpz: only little-endian local hosts are supported");
	if (expectedFrames !== undefined && (!Number.isSafeInteger(expectedFrames) || expectedFrames < 1)) {
		throw new Error("writeLocalKimodoNpz: expectedFrames must be a positive integer");
	}
	const roots = readFloats(join(outputDir, "root_positions.f32"));
	if (roots.length % 3 !== 0) {
		throw new Error("writeLocalKimodoNpz: root_positions.f32 must contain complete XYZ frames");
	}
	const frames = roots.length / 3;
	if (expectedFrames !== undefined && frames !== expectedFrames) {
		throw new Error(`writeLocalKimodoNpz: expected ${expectedFrames} frames, root_positions.f32 contains ${frames}`);
	}
	const quaternions = readFloats(join(outputDir, "local_rotations_xyzw.f32"));
	if (quaternions.length !== frames * 30 * 4) {
		throw new Error(`writeLocalKimodoNpz: local_rotations_xyzw.f32 must contain ${frames} frames of 30 SOMA joints (${frames * 30 * 16} bytes), got ${quaternions.byteLength} bytes`);
	}
	const posedJoints = new Float32Array(frames * 77 * 3);
	const globalRotMats = new Float32Array(frames * 77 * 9);
	const locals = new Array(77);
	for (const [joint, matrix] of RELAXED_LOCALS) locals[joint] = matrix;
	for (let frame = 0; frame < frames; frame++) {
		for (let joint = 0; joint < 30; joint++) {
			locals[SOMA30_TO_77[joint]] = quaternionMatrix(quaternions, (frame * 30 + joint) * 4, frame, joint);
		}
		// Keep intermediate FK in double precision; serialize only the final arrays.
		const globals = new Array(77);
		const positions = new Array(77);
		for (let joint = 0; joint < 77; joint++) {
			const parent = PARENTS[joint];
			if (parent < 0) {
				globals[joint] = locals[joint];
				positions[joint] = Array.from(roots.subarray(frame * 3, frame * 3 + 3));
			} else {
				const a = globals[parent], b = locals[joint], offset = OFFSETS[joint];
				const rotation = new Array(9).fill(0);
				const position = positions[parent].slice();
				for (let row = 0; row < 3; row++) {
					for (let k = 0; k < 3; k++) {
						position[row] += a[row * 3 + k] * offset[k];
						for (let col = 0; col < 3; col++) rotation[row * 3 + col] += a[row * 3 + k] * b[k * 3 + col];
					}
				}
				globals[joint] = rotation;
				positions[joint] = position;
			}
			posedJoints.set(positions[joint], (frame * 77 + joint) * 3);
			globalRotMats.set(globals[joint], (frame * 77 + joint) * 9);
		}
	}
	writeNpz(npzPath, {
		posed_joints: { data: posedJoints, shape: [frames, 77, 3] },
		global_rot_mats: { data: globalRotMats, shape: [frames, 77, 3, 3] },
		fps: { data: new Int32Array([30]), shape: [] },
	});
}
